import React, { useState, useMemo } from "react";
import { motion } from "framer-motion";
import PortalLayout from "@/components/PortalLayout";
import { jsPDF } from "jspdf";
import { DollarSign, TrendingUp, Wallet, Download, FileText, Calendar, Sparkles } from "lucide-react";
import { AreaChart, Area, XAxis, YAxis, ResponsiveContainer, Tooltip, CartesianGrid } from "recharts";

const reports = [
  { month: "September 2026", key: "Sep", cashback: 89.2, savings: 412, redemptions: 24 },
  { month: "August 2026", key: "Aug", cashback: 76.5, savings: 358, redemptions: 20 },
  { month: "July 2026", key: "Jul", cashback: 64.0, savings: 297, redemptions: 17 },
  { month: "June 2026", key: "Jun", cashback: 51.3, savings: 241, redemptions: 14 },
];

export default function MonthlyReports() {
  const [active, setActive] = useState(reports[0]);

  const chart = useMemo(() => reports.slice().reverse(), []);

  const generate = (r) => {
    const doc = new jsPDF();
    doc.setFontSize(20);
    doc.setTextColor(15, 23, 42);
    doc.text("Nelvin Benefits — Monthly Report", 14, 20);
    doc.setFontSize(12);
    doc.setTextColor(100, 116, 139);
    doc.text(r.month, 14, 30);
    doc.setDrawColor(226, 232, 240);
    doc.line(14, 34, 196, 34);

    doc.setTextColor(15, 23, 42);
    doc.setFontSize(13);
    doc.text("Summary", 14, 44);
    doc.setFontSize(11);
    doc.setTextColor(71, 85, 105);
    doc.text(`Total cashback earned:  $${r.cashback.toFixed(2)}`, 14, 54);
    doc.text(`Total savings generated: $${r.savings}`, 14, 62);
    doc.text(`Deals redeemed:          ${r.redemptions}`, 14, 70);
    doc.text(`Avg saving per redemption: $${(r.savings / r.redemptions).toFixed(2)}`, 14, 78);

    doc.setFontSize(13);
    doc.setTextColor(15, 23, 42);
    doc.text("Top categories", 14, 92);
    doc.setFontSize(11);
    doc.setTextColor(71, 85, 105);
    const cats = [["Dining", "$142"], ["Wellness", "$98"], ["Fitness", "$64"], ["Hotels", "$108"]];
    cats.forEach((c, i) => doc.text(`${c[0]}: ${c[1]}`, 14, 102 + i * 8));

    doc.setFontSize(9);
    doc.setTextColor(148, 163, 184);
    doc.text("Generated by Nelvin Benefits — all amounts in USD.", 14, 280);
    doc.save(`Nelvin-Report-${r.key}.pdf`);
  };

  return (
    <PortalLayout title="Monthly Reports" theme="light">
      <div className="mb-4">
        <h1 className="text-xl font-bold text-slate-900">Monthly savings reports</h1>
        <p className="text-sm text-slate-500">Generate and download PDF summaries of your cashback and savings activity.</p>
      </div>

      {/* Active summary */}
      <motion.div initial={{ opacity: 0, y: 12 }} animate={{ opacity: 1, y: 0 }} className="rounded-3xl bg-gradient-to-br from-emerald-500 to-emerald-700 p-6 text-white shadow-lg">
        <div className="flex flex-wrap items-center justify-between gap-4">
          <div>
            <p className="flex items-center gap-2 text-sm text-emerald-50"><Calendar className="h-4 w-4" /> {active.month}</p>
            <div className="mt-3 grid grid-cols-3 gap-6">
              <div><p className="text-3xl font-extrabold">${active.cashback.toFixed(2)}</p><p className="text-xs text-emerald-50">Cashback</p></div>
              <div><p className="text-3xl font-extrabold">${active.savings}</p><p className="text-xs text-emerald-50">Savings</p></div>
              <div><p className="text-3xl font-extrabold">{active.redemptions}</p><p className="text-xs text-emerald-50">Redemptions</p></div>
            </div>
          </div>
          <button onClick={() => generate(active)} className="flex items-center gap-2 rounded-full bg-white px-5 py-3 text-sm font-bold text-emerald-700 hover:bg-emerald-50">
            <Download className="h-4 w-4" /> Download PDF
          </button>
        </div>
      </motion.div>

      {/* Trend chart */}
      <motion.div initial={{ opacity: 0, y: 12 }} whileInView={{ opacity: 1, y: 0 }} viewport={{ once: true }} className="mt-6 rounded-2xl border border-slate-200 bg-white p-5 shadow-sm">
        <h3 className="flex items-center gap-2 font-semibold text-slate-900"><TrendingUp className="h-5 w-5 text-emerald-600" /> Savings trend</h3>
        <div className="mt-4 h-56">
          <ResponsiveContainer width="100%" height="100%">
            <AreaChart data={chart}>
              <defs><linearGradient id="repG" x1="0" y1="0" x2="0" y2="1"><stop offset="0%" stopColor="#10B981" stopOpacity={0.35} /><stop offset="100%" stopColor="#10B981" stopOpacity={0} /></linearGradient></defs>
              <CartesianGrid strokeDasharray="3 3" stroke="#f1f5f9" />
              <XAxis dataKey="key" stroke="#94a3b8" fontSize={12} />
              <YAxis stroke="#94a3b8" fontSize={12} />
              <Tooltip contentStyle={{ borderRadius: 12, border: "1px solid #e2e8f0" }} />
              <Area type="monotone" dataKey="savings" stroke="#10B981" fill="url(#repG)" strokeWidth={2} />
            </AreaChart>
          </ResponsiveContainer>
        </div>
      </motion.div>

      {/* Report list */}
      <motion.div initial={{ opacity: 0, y: 12 }} whileInView={{ opacity: 1, y: 0 }} viewport={{ once: true }} className="mt-6 rounded-2xl border border-slate-200 bg-white p-5 shadow-sm">
        <h3 className="flex items-center gap-2 font-semibold text-slate-900"><FileText className="h-5 w-5 text-emerald-600" /> Past reports</h3>
        <div className="mt-4 space-y-2">
          {reports.map((r) => (
            <div key={r.key} className={`flex flex-col gap-3 rounded-xl border p-4 transition sm:flex-row sm:items-center sm:justify-between ${active.key === r.key ? "border-emerald-300 bg-emerald-50" : "border-slate-200 bg-slate-50"}`}>
              <div className="flex items-center gap-3">
                <span className="flex h-10 w-10 items-center justify-center rounded-lg bg-white text-emerald-600 ring-1 ring-slate-200"><FileText className="h-5 w-5" /></span>
                <div>
                  <p className="text-sm font-medium text-slate-900">{r.month}</p>
                  <p className="text-xs text-slate-500">${r.cashback.toFixed(2)} cashback · ${r.savings} saved · {r.redemptions} deals</p>
                </div>
              </div>
              <div className="flex items-center gap-2">
                <button onClick={() => setActive(r)} className={`rounded-full px-4 py-2 text-xs font-medium ${active.key === r.key ? "bg-emerald-500 text-white" : "border border-slate-200 bg-white text-slate-600 hover:bg-slate-50"}`}>View</button>
                <button onClick={() => generate(r)} className="flex items-center gap-1 rounded-full bg-brand px-4 py-2 text-xs font-medium text-white hover:bg-brand"><Download className="h-3.5 w-3.5" /> PDF</button>
              </div>
            </div>
          ))}
        </div>
      </motion.div>
    </PortalLayout>
  );
}